DROP TABLE IF EXISTS `cmf_comment`;
CREATE TABLE `cmf_comment` (
    `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
    `parent_id` bigint(20) unsigned NOT NULL DEFAULT 0 COMMENT '被回复的评论id',
    `user_id` int(10) unsigned NOT NULL DEFAULT 0 COMMENT '发表评论的用户id',
    `to_user_id` int(10) unsigned NOT NULL DEFAULT 0 COMMENT '被评论的用户id',
    `object_id` int(10) unsigned NOT NULL DEFAULT 0 COMMENT '评论内容 id',
    `like_count` int(10) unsigned NOT NULL DEFAULT 0 COMMENT '点赞数',
    `dislike_count` int(10) unsigned NOT NULL DEFAULT 0 COMMENT '不喜欢数',
    `floor` int(10) unsigned NOT NULL DEFAULT 0 COMMENT '楼层数',
    `create_time` int(10) unsigned NOT NULL DEFAULT 0 COMMENT '评论时间',
    `delete_time` int(10) unsigned NOT NULL DEFAULT 0 COMMENT '删除时间',
    `source` varchar(8) NOT NULL DEFAULT '' COMMENT '评论来源类型',
    `status` tinyint(1) unsigned NOT NULL DEFAULT 1 COMMENT '状态,1:已审核,0:未审核,2:已删除',
    `type` tinyint(1) unsigned NOT NULL DEFAULT 1 COMMENT '评论类型；1实名评论 2小程序反馈',
    `table_name` varchar(64) NOT NULL DEFAULT '' COMMENT '评论内容所在表，不带表前缀',
    `full_name` varchar(64) NOT NULL DEFAULT '' COMMENT '评论者昵称',
    `email` varchar(64) NOT NULL DEFAULT '' COMMENT '评论者邮箱',
    `path` varchar(128) NOT NULL DEFAULT '' COMMENT '层级关系',
    `url` text DEFAULT NULL COMMENT '原文地址',
    `content` text DEFAULT NULL COMMENT '评论内容',
    `more` text DEFAULT NULL COMMENT '扩展属性',
    PRIMARY KEY (`id`),
    KEY `table_id_status` (`table_name`,`object_id`,`status`),
    KEY `object_id` (`object_id`),
    KEY `status` (`status`),
    KEY `parent_id` (`parent_id`),
    KEY `create_time` (`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='评论表'